create or replace function public.audit_record_change() returns trigger language plpgsql security definer set search_path=public,auth as $$
declare v_old jsonb; v_new jsonb; v_id text; v_action text;
begin
  -- Keep the audit trail useful without copying names or phone numbers into a second log.
  if tg_op='DELETE' then
    v_old:=jsonb_build_object('verification_status',old.verification_status,'duplicate_flag',old.duplicate_flag);
    v_new:=null; v_id:=old.record_id; v_action:='RECORD_DELETE';
  elsif tg_op='UPDATE' then
    v_old:=jsonb_build_object('verification_status',old.verification_status,'notes',old.notes);
    v_new:=jsonb_build_object('verification_status',new.verification_status,'notes',new.notes);
    v_id:=new.record_id; v_action:='RECORD_UPDATE';
  else
    v_old:=null; v_new:=jsonb_build_object('position',new.position,'verification_status',new.verification_status,'duplicate_flag',new.duplicate_flag);
    v_id:=new.record_id; v_action:='RECORD_CREATE';
  end if;
  insert into public.audit_log(actor_id,actor_label,action,record_id,old_value,new_value)
  values(auth.uid(),case when auth.uid() is null then 'public-form' else 'admin' end,v_action,v_id,v_old,v_new);
  if tg_op='DELETE' then return old; else return new; end if;
end; $$;
drop trigger if exists coordinator_records_audit on public.coordinator_records;
create trigger coordinator_records_audit after insert or update or delete on public.coordinator_records for each row execute function public.audit_record_change();

create or replace function public.queue_google_sheet_sync() returns trigger language plpgsql security definer set search_path=public as $$
declare v_row jsonb; v_event text; v_id text;
begin
  if tg_op='DELETE' then v_row:=to_jsonb(old); v_event:='DELETE'; v_id:=old.record_id;
  elsif tg_op='UPDATE' then v_row:=to_jsonb(new); v_event:='UPDATE'; v_id:=new.record_id;
  else v_row:=to_jsonb(new); v_event:='INSERT'; v_id:=new.record_id; end if;
  insert into public.sheet_sync_outbox(event_type,record_id,payload) values(v_event,v_id,jsonb_build_object('eventType',v_event,'record',v_row,'recordId',v_id));
  if tg_op='DELETE' then return old; else return new; end if;
end; $$;
drop trigger if exists coordinator_records_sheet_sync on public.coordinator_records;
create trigger coordinator_records_sheet_sync after insert or update or delete on public.coordinator_records for each row execute function public.queue_google_sheet_sync();

