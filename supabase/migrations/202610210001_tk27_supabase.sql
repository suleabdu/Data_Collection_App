-- TK27 Supabase migration (Ogun V1). Run in Supabase SQL Editor before CSV imports.
create extension if not exists pgcrypto;

create table if not exists public.master_geography (
  full_pu_code text primary key,
  state text not null default 'Ogun', state_code text not null default 'OG',
  lga text not null, lga_code text not null, ward text not null, ward_code text not null,
  polling_unit text not null, polling_unit_code text not null,
  status text not null default 'VALID', source text, source_date text, created_at timestamptz, updated_at timestamptz,
  constraint master_lga_code_format check (lga_code ~ '^\d{2}/\d{2}$'),
  constraint master_ward_code_format check (ward_code ~ '^\d{2}/\d{2}/\d{2}$'),
  constraint master_pu_code_format check (full_pu_code ~ '^\d{2}/\d{2}/\d{2}/\d{3}$')
);
create index if not exists idx_master_lga_code on public.master_geography(lga_code);
create index if not exists idx_master_ward_code on public.master_geography(ward_code);
create index if not exists idx_master_status on public.master_geography(status);

create table if not exists public.coordinator_records (
  record_id text primary key,
  state text not null default 'Ogun', state_code text not null default 'OG',
  name text not null, position text not null check (position in ('STATE_EXCO','LGA_COORDINATOR','WARD_COORDINATOR')),
  phone text not null, lga text not null, lga_code text not null, ward text not null, ward_code text not null,
  polling_unit text not null, polling_unit_code text not null,
  verification_status text not null default 'PENDING' check (verification_status in ('PENDING','VERIFIED','REJECTED')),
  duplicate_flag boolean not null default false,
  submitted_at timestamptz not null default now(), updated_at timestamptz not null default now(),
  submitted_by text not null default 'public-form', notes text not null default '', submission_key text,
  normalized_name text not null default '', normalized_phone text not null default ''
);
create unique index if not exists idx_coordinator_submission_key on public.coordinator_records(submission_key) where submission_key is not null and submission_key <> '';
create index if not exists idx_coordinator_submitted_at on public.coordinator_records(submitted_at desc);
create index if not exists idx_coordinator_position on public.coordinator_records(position);
create index if not exists idx_coordinator_status on public.coordinator_records(verification_status);
create index if not exists idx_coordinator_lga_code on public.coordinator_records(lga_code);
create index if not exists idx_coordinator_phone on public.coordinator_records(normalized_phone);
create index if not exists idx_coordinator_normalized_name on public.coordinator_records(normalized_name);

create table if not exists public.app_settings(key text primary key, value text not null, updated_at timestamptz not null default now());
insert into public.app_settings(key,value) values ('ACTIVE_STATE','Ogun'),('STATE_CODE','OG'),('APPLICATION_STATUS','PAUSED') on conflict (key) do nothing;
create table if not exists public.admin_users(user_id uuid primary key references auth.users(id) on delete cascade, email text not null, active boolean not null default true, created_at timestamptz not null default now());
create table if not exists public.record_sequences(prefix text primary key, last_value bigint not null default 0 check (last_value >= 0));
create table if not exists public.audit_log(
  id bigint generated by default as identity primary key, created_at timestamptz not null default now(), actor_id uuid,
  actor_label text not null default 'system', action text not null, record_id text, old_value jsonb, new_value jsonb, result text not null default 'OK'
);
create index if not exists idx_audit_created_at on public.audit_log(created_at desc);
create index if not exists idx_audit_record_id on public.audit_log(record_id);
create table if not exists public.sheet_sync_outbox(
  id bigint generated by default as identity primary key, event_type text not null check (event_type in ('INSERT','UPDATE','DELETE')),
  record_id text not null, payload jsonb not null, status text not null default 'PENDING' check (status in ('PENDING','PROCESSING','SYNCED','FAILED')),
  attempts integer not null default 0, last_error text, created_at timestamptz not null default now(), last_attempt_at timestamptz, synced_at timestamptz
);
create index if not exists idx_sync_outbox_pending on public.sheet_sync_outbox(status,created_at) where status <> 'SYNCED';

create or replace function public.is_tk27_admin() returns boolean language sql stable security definer set search_path=public,auth as $$
  select exists(select 1 from public.admin_users a where a.user_id=auth.uid() and a.active=true);
$$;
revoke all on function public.is_tk27_admin() from public;
grant execute on function public.is_tk27_admin() to anon,authenticated;

